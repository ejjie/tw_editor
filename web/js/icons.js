export function icon(name, size = 16) {
  return `<svg class="ic" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] || ''}</svg>`;
}

export function iconEl(name, size) {
  const t = document.createElement('template');
  t.innerHTML = icon(name, size);
  return t.content.firstChild;
}

export function applyIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.querySelector(':scope > svg.ic')) return;
    el.prepend(iconEl(el.dataset.icon));
    wrapText(el);
  });
}

// the text next to an icon goes into a span that is trimmed to the cap height, so it centres on the icon in any font
export function wrapText(el) {
  for (const n of [...el.childNodes]) {
    if (n.nodeType !== 3 || !n.textContent.trim()) continue;
    const s = document.createElement('span');
    s.className = 'bt';
    n.replaceWith(s);
    s.append(n);
  }
}
